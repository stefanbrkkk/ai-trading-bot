/** Resolves the state band a raw value falls into. */
export function resolveState(definition: FeatureDefinition, value: number): FeatureState {
  for (const band of definition.states) {
    if (value >= band.min && value < band.max) return band;
  }
  return definition.states[definition.states.length - 1] as FeatureState;
}

/** Formats a raw value in its native unit for display. */
export function formatFeatureValue(definition: FeatureDefinition, value: number): string {
  if (!Number.isFinite(value)) return '—';
  const n = value.toFixed(definition.precision);
  switch (definition.unit) {
    case 'percent':
      return `${n}%`;
    case 'bps':
      return `${n} bp`;
    case 'volpoints':
      return `${n} vp`;
    case 'probability':
      return `${(value * 100).toFixed(1)}%`;
    case 'zscore':
      return `${value >= 0 ? '+' : ''}${n}σ`;
    case 'signed_unit':
      return `${value >= 0 ? '+' : ''}${n}`;
    case 'bars':
      return Number.isFinite(value) ? `${n} bars` : '∞';
    case 'currency':
      return `$${Number(n).toLocaleString('en-US')}`;
    case 'shares':
      return Number(value).toLocaleString('en-US');
    case 'index_0_100':
    case 'ratio':
    case 'count':
    default:
      return n;
  }
}
