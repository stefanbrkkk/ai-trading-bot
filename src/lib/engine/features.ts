/**
 * The feature registry.
 *
 * One definition per feature, carrying everything four different subsystems
 * need so they can never drift apart:
 *
 *   1. the model — `inModel` selects the ordered vector fed to the GBDT and the
 *      three temporal agents;
 *   2. the XAI translation engine — `states` is the deterministic mapping matrix
 *      Phase 4 §1 mandates: discretise the raw value into a state, then hydrate
 *      an authoritative narrative template. No LLM is involved, and no maths
 *      happens on the client;
 *   3. InvestGPT — `aliases`, `sqlColumn` and `description` are what CSR-RAG
 *      retrieves over when pruning the schema;
 *   4. the UI — `label`, `unit` and `format` render the drill-down table.
 *
 * Adding a feature in one place therefore adds it everywhere, consistently.
 */

import type { FeatureGroup, FeatureUnit } from '@/lib/domain/types';

export interface FeatureState {
  /** Machine state label, e.g. STATE_OVERSOLD. */
  state: string;
  /** Inclusive lower bound; −Infinity for open. */
  min: number;
  /** Exclusive upper bound; +Infinity for open. */
  max: number;
  /**
   * Noun phrase describing what the state *is*, e.g.
   * "an exhaustion of sell-side pressure".
   */
  predicate: string;
  /**
   * Clause describing what it implies, e.g.
   * "indicating a high-probability mean reversion".
   */
  implication: string;
  /** Which way this state normally leans. */
  polarity: 'bullish' | 'bearish' | 'neutral';
}

export interface FeatureDefinition {
  key: string;
  label: string;
  /** ≤ 18 chars, for dense tables and chart axes. */
  shortLabel: string;
  group: FeatureGroup;
  unit: FeatureUnit;
  /** One sentence, shown in the schema explorer and on hover. */
  description: string;
  /** Plain-text formula, shown verbatim in the model card. */
  formula: string;
  /** Column in `v_equity_snapshot` that InvestGPT queries. */
  sqlColumn: string;
  /** Synonyms the NL→SQL retriever matches. */
  aliases: string[];
  /** True when the feature is part of the ordered model input vector. */
  inModel: boolean;
  /** Decimal places for display. */
  precision: number;
  /** Ordered state bands; the first whose [min, max) contains the value wins. */
  states: FeatureState[];
}

const B = (
  state: string,
  min: number,
  max: number,
  predicate: string,
  implication: string,
  polarity: FeatureState['polarity'],
): FeatureState => ({ state, min, max, predicate, implication, polarity });

/** Neutral filler band, used where the middle of the range carries no thesis. */
const NEUTRAL = (state: string, min: number, max: number, predicate: string): FeatureState =>
  B(state, min, max, predicate, 'offering no directional edge on its own', 'neutral');

