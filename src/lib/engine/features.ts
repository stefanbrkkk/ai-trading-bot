const BY_KEY = new Map(FEATURE_DEFINITIONS.map((f) => [f.key, f]));

/** Ordered keys of the model input vector — the single source of column order. */
export const MODEL_FEATURE_KEYS: string[] = FEATURE_DEFINITIONS.filter((f) => f.inModel).map((f) => f.key);

export const MODEL_FEATURE_COUNT = MODEL_FEATURE_KEYS.length;

export function featureDefinition(key: string): FeatureDefinition | undefined {
  return BY_KEY.get(key);
}

export function requireFeature(key: string): FeatureDefinition {
  const f = BY_KEY.get(key);
  if (!f) throw new Error(`Unknown feature key: ${key}`);
  return f;
}

export function featuresInGroup(group: FeatureGroup): FeatureDefinition[] {
  return FEATURE_DEFINITIONS.filter((f) => f.group === group);
}

